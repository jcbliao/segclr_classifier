def assemble_deployment(c,p):
    import numpy as np
    import pyarrow as pa
    import pyarrow.parquet as pq
    RAW.mkdir(exist_ok=True,mode=0o2775)
    plan=json.loads((LEGACY/'plan.json').read_text())
    if 'models' in plan:plan['legacy_subcompartment_models']=plan.pop('models')
    plan.update(embedding_run_id=RUN,embedding_checkpoint_id=CHECKPOINT,embedding_checkpoint_sha256=p['checkpoint_sha256'],feature_provenance=str(WORK/'plan.json'),legacy_geometry_plan_sha256=p['old_fragment_plan_sha256'],axon_filter_embedding_run_id='resnet_860b_reshuffled__20260603_150412',axon_filter_policy=p['legacy_axon_filter'])
    save(RAW/'plan.json',plan);digest=sha(RAW/'plan.json')
    for source in sorted((LEGACY/'parts').glob('*/*.parquet')):
        dest=RAW/'parts'/source.parent.name/source.name
        if dest.exists():
            if (pq.read_schema(dest).metadata or {}).get(b'plan_sha256')!=digest.encode():raise ValueError('stale fragment features')
            continue
        table=pq.read_table(source)
        c.register('source_fragment',table)
        # Ordinality preserves the original shortest-path node ordering.
        rows=table.append_column('row_index',pa.array(np.arange(len(table),dtype=np.int64)));c.register('numbered',rows)
        lo=int(np.min(np.asarray(table['partner_root_id'])));hi=int(np.max(np.asarray(table['partner_root_id'])))
        got=c.execute("SELECT t.row_index,u.position,v.embedding FROM numbered t CROSS JOIN LATERAL unnest(t.fragment_node_ids) WITH ORDINALITY AS u(node_id,position) JOIN deployment_nodes n ON t.partner_root_id=n.root_id AND u.node_id=n.node_id JOIN (SELECT * FROM vectors WHERE root_id BETWEEN ? AND ?) v ON v.root_id=n.root_id AND v.x=n.x_nm AND v.y=n.y_nm AND v.z=n.z_nm WHERE t.status='ready' ORDER BY t.row_index,u.position",[lo,hi]).to_arrow_table()
        counts=np.where(np.asarray(table['status'])=='ready',np.asarray(table['n_embeddings_used'],np.int64),0)
        if len(got)!=counts.sum():raise ValueError('fragment node vectors missing')
        values=np.asarray(got['embedding'].combine_chunks().values,np.float32).reshape(-1,64)
        offsets=np.r_[0,np.cumsum(counts)].astype(np.int32)
        raw=pa.ListArray.from_arrays(pa.array(offsets),pa.FixedSizeListArray.from_arrays(pa.array(values.reshape(-1)),64))
        means=np.zeros((len(table),64),np.float32)
        for i in np.flatnonzero(counts):means[i]=values[offsets[i]:offsets[i+1]].mean(0,dtype=np.float64)
        table=table.set_column(table.schema.get_field_index('fragment_embeddings'),'fragment_embeddings',raw)
        table=table.set_column(table.schema.get_field_index('mean_embedding'),'mean_embedding',pa.FixedSizeListArray.from_arrays(pa.array(means.reshape(-1)),64))
        metadata=dict(table.schema.metadata or {});metadata[b'plan_sha256']=digest.encode();metadata[b'feature_run_id']=RUN.encode()
        table=table.replace_schema_metadata(metadata)
        dest.parent.mkdir(parents=True,exist_ok=True);pq.write_table(table,dest,compression='zstd')
    (RAW/'postsynaptic_points').mkdir(exist_ok=True)
    for source in sorted((LEGACY/'postsynaptic_points').glob('*.parquet')):
        dest=RAW/'postsynaptic_points'/source.name
        if dest.exists():continue
        table=pq.read_table(source);xyz=np.asarray(table['post_position_nm'].combine_chunks().values,np.float32).reshape(-1,3)
        root=int(np.asarray(table['cell_root_id'])[0]);values=vectors_at(c,root,xyz)
        table=table.set_column(table.schema.get_field_index('post_embedding'),'post_embedding',pa.FixedSizeListArray.from_arrays(pa.array(values.reshape(-1)),64))
        md=dict(table.schema.metadata or {});md[b'plan_sha256']=digest.encode();md[b'feature_run_id']=RUN.encode()
        pq.write_table(table.replace_schema_metadata(md),dest,compression='zstd')
    for name in ('cohort','summary.json'):
        if not (RAW/name).exists():(RAW/name).symlink_to(LEGACY/name,target_is_directory=(LEGACY/name).is_dir())
    for rank in range(32):
        files=sorted((RAW/'parts'/f'{rank:03d}').glob('*.parquet'))
        previous=json.loads((LEGACY/'status'/f'{rank:03d}_complete.json').read_text())
        rows=sum(pq.ParquetFile(path).metadata.num_rows for path in files)
        if rows!=previous['synapses'] or len(files)!=previous['parts']:raise ValueError('assembled raw shard incomplete')
        previous.update(plan_sha256=digest,feature_run_id=RUN)
        save(RAW/'status'/f'{rank:03d}_complete.json',previous)
    # The original view points at legacy vectors; build a new self-contained view.
    import duckdb
    with duckdb.connect(str(RAW/'fragments.duckdb')) as view:
        view.read_parquet(str(RAW/'parts/*/*.parquet')).create_view('fragments',replace=True)
        view.execute("CREATE OR REPLACE VIEW classified_fragments AS SELECT * FROM fragments WHERE status='ready'")
    save(RAW/'feature_complete.json',dict(run_id=RUN,checkpoint_sha256=p['checkpoint_sha256'],plan_sha256=digest,legacy_axon_gate_retained=True))


def assemble():
    with open_db(read_only=True) as c:
        p=create_feature_view(c)
        archive=WORK/'vector_archive'
        if not (archive/'complete.json').exists():
            if archive.exists():raise ValueError('incomplete vector archive requires inspection')
            bad=c.sql('SELECT count(*) FROM vectors WHERE embedding IS NULL OR len(embedding)!=64 OR NOT isfinite(list_sum(embedding))').fetchone()[0]
            if bad:raise ValueError('invalid cached/generated feature vectors')
            temp=WORK/'vector_archive.tmp'
            if temp.exists():raise ValueError('partial vector archive requires inspection')
            print('archiving vectors in root order for bounded feature lookup',flush=True)
            c.sql('SELECT * FROM vectors ORDER BY root_id,x,y,z').write_parquet(str(temp),compression='zstd',row_group_size=8192,per_thread_output=True)
            temp.rename(archive)
            save(archive/'complete.json',dict(run_id=RUN,points=p['points'],checkpoint_sha256=p['checkpoint_sha256']))
        c.read_parquet(str(archive/'*.parquet')).create_view('archived_vectors')
        c.execute('CREATE OR REPLACE TEMP VIEW vectors AS SELECT * FROM archived_vectors')
        assemble_training(c,p)
