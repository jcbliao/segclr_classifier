def append_points(c,roots,xyz):
    import numpy as np
    import pyarrow as pa
    xyz=np.asarray(xyz,np.float32)
    if not np.isfinite(xyz).all():raise ValueError('nonfinite request coordinates')
    t=pa.table(dict(root_id=np.asarray(roots,np.int64),x=xyz[:,0],y=xyz[:,1],z=xyz[:,2]))
    c.register('new_points',t)
    c.execute('INSERT INTO requests SELECT * FROM new_points')
    c.unregister('new_points')


