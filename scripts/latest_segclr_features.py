    receipt=dict(run_id=RUN,checkpoint_sha256=p['checkpoint_sha256'],training_base=str(NEW_BASE),training_post=str(NEW_POST),scope='training_only' if TRAINING_ONLY else 'training_and_deployment')
    if not TRAINING_ONLY:receipt.update(raw_input=str(RAW),output=str(OUTPUT))
    save(WORK/'complete.json',receipt)
    print('LATEST SEGCLR FEATURES ASSEMBLED',flush=True)


