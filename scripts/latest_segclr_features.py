def embed_table(model,table):
    import numpy as np
    roots=np.asarray(table['root_id'],np.int64);ids=np.asarray(table['point_id'],np.int64)
    xyz=np.column_stack([np.asarray(table[a],np.float32) for a in ('x','y','z')])
    centers=model.crops.nm_to_voxel(xyz)
    keys,vectors,failed=model._run_batches(roots,centers,ids)
    if failed or len(keys)!=len(ids):raise RuntimeError(f'incomplete crops: {len(keys)}/{len(ids)}, {failed} failures')
    keys=np.asarray(keys,np.int64);vectors=np.asarray(vectors,np.float32)
    order=np.argsort(keys[:,1]);keys=keys[order];vectors=vectors[order]
    wanted=np.argsort(ids)
    np.testing.assert_array_equal(keys[:,1],ids[wanted]);np.testing.assert_array_equal(keys[:,0],roots[wanted])
    if vectors.shape!=(len(ids),64) or not np.isfinite(vectors).all():raise ValueError('invalid vectors')
    return ids[wanted],vectors


def smoke():
    import numpy as np
    import pyarrow as pa
    model=engine()
    try:
        with open_db(read_only=True) as c:
            sample=c.sql('SELECT p.*,c.embedding FROM cached c JOIN points p USING(point_id) ORDER BY p.point_id LIMIT 32').to_arrow_table()
            if len(sample):
                ids,vectors=embed_table(model,sample)
                expected=np.asarray(sample.take(pa.array(np.argsort(np.asarray(sample['point_id']))))['embedding'].combine_chunks().values).reshape(-1,64)
                # TF32 convolution kernels vary with GPU and batch shape.
                # Compare vector magnitude/direction instead of relative error
                # at individual near-zero components.
                actual64=vectors.astype(np.float64);expected64=expected.astype(np.float64)
                norms=np.linalg.norm(expected64,axis=1)
                relative=np.linalg.norm(actual64-expected64,axis=1)/np.maximum(norms,1e-12)
                cosine=np.sum(actual64*expected64,axis=1)/np.maximum(np.linalg.norm(actual64,axis=1)*norms,1e-12)
                error=float(np.max(np.abs(vectors-expected)))
                if np.max(relative)>0.002 or np.min(cosine)<0.999998 or error>0.005:
                    raise ValueError(f'cached preprocessing mismatch: relative L2={relative.max()}, cosine={cosine.min()}, abs={error}')
            else:
                sample=c.sql('SELECT * FROM points LIMIT 8').to_arrow_table();embed_table(model,sample);error=None
        save(WORK/'preprocessing_parity.json',dict(passed=True,run_id=RUN,checkpoint_sha256=sha(WEIGHTS),cached_points_tested=len(sample),max_absolute_error=error,
            comparison='cached vectors versus pinned checkpoint with upstream two-channel normalization and CLAHE/segmentation registry crops; TF32 tolerances: relative L2<=0.002, cosine>=0.999998, max absolute<=0.005'))
        print('LATEST SEGCLR GPU/PREPROCESSING PARITY PASSED',error,flush=True)
    finally:model.close()


def embed(rank,world):
    import numpy as np
    import pyarrow as pa
    import pyarrow.parquet as pq
    import fcntl
    p=json.loads((WORK/'plan.json').read_text())
    parity=json.loads((WORK/'preprocessing_parity.json').read_text())
    if not parity['passed'] or parity['checkpoint_sha256']!=p['checkpoint_sha256']:raise ValueError('GPU parity prerequisite failed')
    (WORK/'embeddings').mkdir(exist_ok=True)
    model=engine();started=time.monotonic()
    try:
        for i,item in enumerate(p['chunks']):
            if i%world!=rank:continue
            dest=WORK/'embeddings'/Path(item['path']).name
            with dest.with_suffix('.lock').open('w') as lock:
                fcntl.flock(lock,fcntl.LOCK_EX)
                if sha(item['path'])!=item['sha256']:raise ValueError('request shard changed')
                if dest.exists():
                    md=pq.read_schema(dest).metadata or {}
                    if md.get(b'checkpoint_sha256')!=p['checkpoint_sha256'].encode() or pq.ParquetFile(dest).metadata.num_rows!=item['rows']:raise ValueError('stale feature shard')
                    continue
                ids,vectors=embed_table(model,pq.read_table(item['path']))
                table=pa.table(dict(point_id=pa.array(ids),embedding=pa.FixedSizeListArray.from_arrays(pa.array(vectors.reshape(-1)),64))).replace_schema_metadata({b'checkpoint_sha256':p['checkpoint_sha256'].encode()})
                temp=dest.with_suffix('.tmp.parquet');pq.write_table(table,temp,compression='zstd');temp.replace(dest)
                print('embedded',i,len(ids),'elapsed',time.monotonic()-started,flush=True)
    finally:model.close()
    save(WORK/'status'/f'worker_{rank:02d}.json',dict(complete=True,rank=rank,world=world,checkpoint_sha256=p['checkpoint_sha256']))


def create_feature_view(c):
    import pyarrow as pa
    import pyarrow.parquet as pq
    p=json.loads((WORK/'plan.json').read_text())
    paths=[]
    for item in p['chunks']:
        path=WORK/'embeddings'/Path(item['path']).name
        md=pq.read_schema(path).metadata or {}
        if md.get(b'checkpoint_sha256')!=p['checkpoint_sha256'].encode() or pq.ParquetFile(path).metadata.num_rows!=item['rows']:raise ValueError('incomplete or stale regenerated features')
        paths.append(str(path))
    if paths:c.read_parquet(paths).create_view('generated')
    else:c.register('generated',pa.table({'point_id':pa.array([],pa.int64()),'embedding':pa.array([],pa.list_(pa.float32(),64))}))
    c.execute('CREATE OR REPLACE TEMP VIEW features AS SELECT * FROM cached UNION ALL SELECT * FROM generated')
    n,unique=c.sql('SELECT count(*),count(DISTINCT point_id) FROM features').fetchone()
    if n!=p['points'] or n!=unique:raise ValueError('missing or duplicate feature identities')
    c.execute('CREATE OR REPLACE TEMP VIEW vectors AS SELECT p.*,f.embedding FROM points p JOIN features f USING(point_id)')
    return p


def vectors_at(c,root,xyz):
    import numpy as np
    import pyarrow as pa
    xyz=np.asarray(xyz,np.float32)
    c.register('locations',pa.table(dict(ordinal=np.arange(len(xyz),dtype=np.int64),root_id=np.repeat(root,len(xyz)).astype(np.int64),x=xyz[:,0],y=xyz[:,1],z=xyz[:,2])))
    # A literal root filter prunes the archive's sorted Parquet row groups.
    table=c.execute('SELECT l.ordinal,v.embedding FROM locations l LEFT JOIN (SELECT * FROM vectors WHERE root_id=?) v USING(root_id,x,y,z) ORDER BY l.ordinal',[root]).to_arrow_table()
    c.unregister('locations')
    if len(table)!=len(xyz) or table['embedding'].null_count:raise ValueError('unresolved feature coordinates')
    values=np.asarray(table['embedding'].combine_chunks().values,np.float32).reshape(-1,64)
    if not np.isfinite(values).all():raise ValueError('nonfinite assembled vectors')
    return values


